export const menuAnalytics = Object.fromEntries(
    Object.entries(RAW).map(([period, rows]) => [
        period,
        rows.map(([menuId, sold, views, addedToCart]) => {
            const menu = menuById[menuId];
            return { menuId, sold, views, addedToCart, revenue: sold * menu.price, profit: sold * (menu.price - menu.hpp) };
        }),
    ]),
);
